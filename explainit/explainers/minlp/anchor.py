"""Stage 1: find the anchor (target exemplar).

The anchor is a point near the target that respects the priorities. The
surrogate is linearised towards it, so it fixes the direction of the search.
It is taken from the dataset when possible, otherwise generated by sampling
the allowed region.
"""

from typing import Any

import numpy as np

from explainit._random import NumpyRandom
from explainit.explainers.minlp._types import Combination, Group, Vector
from explainit.explainers.minlp.intervals import in_allowed_intervals
from explainit.explainers.minlp.state import PrioritiesState
from explainit.logging_config import logger
from explainit.typing import FloatArray, Model


def filter_rows(dataset: FloatArray, priorities_state: PrioritiesState) -> FloatArray:
    """Dataset rows that respect the priorities.

    Drops rows with a forbidden (``None``) categorical combination and rows
    whose mutable numerical features are outside their bounds or allowed
    intervals. Immutable features are not checked (known issue MINLP-3).

    Raises:
        Exception: If no row is left.
    """

    def remove_combination(rows: FloatArray, group: Group, values: Combination) -> FloatArray:
        mask = ~(np.all(rows[:, group] == values, axis=1))
        filtered: FloatArray = rows[mask]
        return filtered

    logger.info(
        "[Stage 1.1] Filtering dataset (%d rows) using priority "
        "constraints (categorical None entries + numerical bounds)...",
        dataset.shape[0],
    )
    rows = dataset.copy()

    forbidden = [
        (group, values)
        for group, mapping in priorities_state.categorical_priorities.items()
        for values, weight in mapping.items()
        if weight is None
    ]
    if forbidden:
        logger.info(
            "[Stage 1.1a] Dropping rows matching disallowed categorical combos: %d combo(s)",
            len(forbidden),
        )
    for group, values in forbidden:
        rows = remove_combination(rows, group, values)
        if rows.size == 0:
            raise Exception("There are no elements fulfilling the requirements")
    logger.info("[Stage 1.1a] After categorical filtering: %d rows remain.", rows.shape[0])

    immutable = priorities_state.non_actionable_indices
    for idx, (min_val, max_val) in priorities_state.bounds.items():
        if idx in immutable:
            continue
        if min_val is not None:
            rows = rows[rows[:, idx] >= min_val]
        if max_val is not None:
            rows = rows[rows[:, idx] <= max_val]
        if rows.size == 0:
            raise Exception("There are no elements fulfilling the requirements")
        cfg = priorities_state.numerical_priorities.get(idx, {})
        allowed_intervals = cfg.get("allowed_intervals") if isinstance(cfg, dict) else None
        if allowed_intervals:
            in_interval = np.array(
                [in_allowed_intervals(float(v), allowed_intervals) for v in rows[:, idx]],
                dtype=bool,
            )
            rows = rows[in_interval]
            if rows.size == 0:
                raise Exception("There are no elements fulfilling the requirements")
    logger.info("[Stage 1.1b] After numerical bound filtering: %d rows remain.", rows.shape[0])

    return rows


def closest_row(model: Model, rows: FloatArray, target: float, tolerance: float) -> FloatArray:
    """The row whose prediction is closest to ``target``.

    Raises:
        ValueError: If the closest prediction is further than ``tolerance``.
        AssertionError: If several rows are equally close (known issue MINLP-7).
    """
    logger.info(
        "[Stage 1.2] Searching the priority-filtered dataset for the row "
        "whose model prediction best matches target=%.4f...",
        float(target),
    )
    pred = model(rows)

    min_dist = np.abs(pred - target).min()
    logger.info(
        "[Stage 1.2] Closest filtered-row prediction is %.4f away from target.", float(min_dist)
    )
    if min_dist > tolerance:
        raise ValueError(
            f"No elements found within the specified epsilon of {tolerance}. Closest distance is {min_dist}."
        )

    idx_all = np.where(np.abs(pred - target) == min_dist)[0]
    assert len(idx_all) == 1, "Expected exactly one target exemplar index, but found multiple."
    logger.info(
        "[Stage 1.2] Target exemplar locked in (filtered idx=%d, prediction=%.4f).",
        int(idx_all[0]),
        float(pred[idx_all[0]]),
    )
    exemplar: FloatArray = rows[idx_all[0]]
    return exemplar


def sample_from_allowed_region(config: Any, rng: NumpyRandom) -> float:
    """A uniform value from a numerical feature's allowed region."""
    intervals = config.get("allowed_intervals") if isinstance(config, dict) else None
    if not intervals:
        lo = config.get("min")
        hi = config.get("max")
        if lo is None or hi is None:
            raise Exception("Feature has no allowed region to sample from.")
        return float(rng.uniform(float(lo), float(hi)))
    lengths = np.array([max(0.0, float(hi) - float(lo)) for lo, hi in intervals], dtype=float)
    total = float(lengths.sum())
    if total <= 0.0:
        lo, _hi = intervals[int(rng.randint(len(intervals)))]
        return float(lo)
    pick = intervals[int(rng.choice(len(intervals), p=lengths / total))]
    return float(rng.uniform(float(pick[0]), float(pick[1])))


def sample_candidate(
    sample: Vector, priorities_state: PrioritiesState, rng: NumpyRandom
) -> FloatArray:
    """One random point inside the allowed region.

    Mutable numerical features are uniform over their allowed region, mutable
    categorical groups pick uniformly among allowed combinations (priorities
    are ignored on purpose), and immutable features keep the sample's value.
    """
    sample = np.asarray(sample, dtype=float)
    candidate = sample.copy()
    for idx, cfg in priorities_state.numerical_priorities.items():
        if not isinstance(cfg, dict) or cfg.get("function") is None:
            candidate[idx] = float(sample[idx])
            continue
        candidate[idx] = sample_from_allowed_region(cfg, rng)
    for group, mapping in priorities_state.categorical_priorities.items():
        allowed = [
            combo for combo, weight in mapping.items() if weight is not None and float(weight) > 0.0
        ]
        if not allowed:
            raise Exception(
                f"Categorical group {group} has no allowed combinations to sample from."
            )
        combo = allowed[int(rng.randint(len(allowed)))]
        for j, idx in enumerate(group):
            candidate[idx] = float(combo[j])
    return candidate


def _prediction(model: Model, candidate: FloatArray) -> float:
    return float(np.asarray(model(candidate.reshape(1, -1))).reshape(-1)[0])


def generate_in_range(
    model: Model,
    sample: Vector,
    priorities_state: PrioritiesState,
    target: float,
    epsilon: float,
    max_iterations: int,
    rng: NumpyRandom,
) -> tuple[FloatArray, float]:
    """The first random point of the allowed region within ``epsilon`` of ``target``.

    Priorities are ignored: this only provides a reachable anchor, which the
    optimisation then improves.

    Returns:
        tuple: ``(candidate, |prediction - target|)``.

    Raises:
        Exception: If no point is found within ``max_iterations`` samples.
    """
    logger.info(
        "[Stage 1 - fallback] Randomly generating an in-range exemplar: "
        "sampling the allowed region for a point within epsilon=%.4f of "
        "target (max_iterations=%d).",
        float(epsilon),
        int(max_iterations),
    )
    for i in range(int(max_iterations)):
        candidate = sample_candidate(sample, priorities_state, rng)
        pred = _prediction(model, candidate)
        if abs(pred - float(target)) <= float(epsilon):
            logger.info(
                "[Stage 1 - fallback] In-range exemplar found at iteration "
                "%d (|pred - target|=%.4f).",
                i + 1,
                abs(pred - float(target)),
            )
            return candidate, abs(pred - float(target))

    raise Exception(
        f"Could not randomly generate an in-range point within "
        f"epsilon={epsilon} of target after {max_iterations} "
        f"iterations."
    )


def probe_feasibility(
    model: Model,
    sample: Vector,
    priorities_state: PrioritiesState,
    target: float,
    epsilon: float,
    max_iterations: int,
    rng: NumpyRandom,
) -> dict[str, Any]:
    """Whether random points of the allowed region can reach the target.

    Returns:
        dict: ``feasible_within_epsilon``, ``min_pred_distance`` and
        ``iterations_run``.
    """
    min_dist = float("inf")
    found_iter = None
    for i in range(int(max_iterations)):
        candidate = sample_candidate(sample, priorities_state, rng)
        dist = abs(_prediction(model, candidate) - float(target))
        if dist < min_dist:
            min_dist = dist
        if dist <= float(epsilon):
            found_iter = i + 1
            break
    return {
        "feasible_within_epsilon": found_iter is not None,
        "min_pred_distance": float(min_dist),
        "iterations_run": int(found_iter if found_iter is not None else max_iterations),
    }
